# --------------------------------------------------------------------------- npm


def _get(url: str, timeout: float = 60) -> bytes:
    if not url.startswith("https://"):
        raise SystemExit(f"refusing a non-HTTPS URL: {url}")
    req = urllib.request.Request(url, headers={"User-Agent": "baleen-vendor-assets"})
    with urllib.request.urlopen(req, timeout=timeout) as r:  # noqa: S310 - https only (checked)
        return r.read()


def registry_meta(name: str, version: str) -> dict:
    quoted = urllib.parse.quote(name, safe="@/")
    return json.loads(_get(f"{REGISTRY}/{quoted}/{version}"))


def sri_sha512(data: bytes) -> str:
    return "sha512-" + base64.b64encode(hashlib.sha512(data).digest()).decode()


def fetch_package(name: str, pin: dict, cache: Path) -> Path:
    """Download (or reuse) a verified tarball; return the unpacked package folder."""
    version = pin["version"]
    safe = name.replace("@", "").replace("/", "__")
    tgz = cache / f"{safe}-{version}.tgz"
    meta = registry_meta(name, version)
    reg_integrity = meta["dist"]["integrity"]
    url = meta["dist"]["tarball"]
    if not url.startswith(REGISTRY + "/"):
        raise SystemExit(f"{name}: unexpected tarball URL {url}")
    if pin.get("integrity") and pin["integrity"] != reg_integrity:
        raise SystemExit(f"{name}@{version}: registry integrity {reg_integrity} differs from the pin")
    expected = pin.get("integrity") or reg_integrity
    if tgz.exists() and sri_sha512(tgz.read_bytes()) != expected:
        tgz.unlink()
    if not tgz.exists():
        data = _get(url, timeout=300)
        if sri_sha512(data) != expected:
            raise SystemExit(f"{name}@{version}: tarball does not match its sha512 integrity")
        tgz.parent.mkdir(parents=True, exist_ok=True)
        tmp = tgz.with_suffix(".part")
        tmp.write_bytes(data)
        os.replace(tmp, tgz)
    dest = cache / "unpacked" / f"{safe}-{version}"
    if not (dest / "package" / "package.json").exists():
        if dest.exists():
            shutil.rmtree(dest)
        dest.mkdir(parents=True)
        with tarfile.open(tgz, "r:gz") as tf:
            tf.extractall(dest, filter="data")
    return dest / "package"


def pin_integrity(pins: dict) -> None:
    for name, pin in pins["npm"].items():
        meta = registry_meta(name, pin["version"])
        pin["integrity"] = meta["dist"]["integrity"]
        print(f"pinned {name}@{pin['version']} {pin['integrity'][:24]}…")
    PINS.write_text(json.dumps(pins, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# --------------------------------------------------------------------------- prototype parts


def prototype_parts() -> dict[str, str]:
    html = PROTOTYPE.read_text(encoding="utf-8")
    style = re.search(r"<style>\n?(.*?)</style>", html, re.S)
    sprite = re.search(r'(<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">.*?</svg>)',
                       html, re.S)
    favicon = re.search(r'<link rel="icon" type="image/svg\+xml" href="data:image/svg\+xml;base64,([A-Za-z0-9+/=]+)">',
                        html)
    logo = re.search(r'var WW_LOGO="data:image/png;base64,([A-Za-z0-9+/=]+)"', html)
    if not (style and sprite and favicon and logo):
        raise SystemExit("prototype layout changed: style, sprite, favicon or logo not found")
    return {"style": style.group(1), "sprite": sprite.group(1), "favicon": favicon.group(1), "logo": logo.group(1)}


def build_css(style: str, out: Path) -> None:
    lines = style.splitlines()
    kept: list[str] = []
    for line in lines:
        s = line.strip()
        if s.startswith(".gal ") or s.startswith(".gal{") or s == "/* gallery (design reference route) */":
            continue
        kept.append(line)
    css = "\n".join(kept).strip("\n") + "\n"
    chevron = re.search(r'url\("data:image/svg\+xml,([^"]+)"\)', css)
    if not chevron:
        raise SystemExit("select chevron data: URI not found in the prototype CSS")
    svg = urllib.parse.unquote(chevron.group(1))
    (out / "select-chevron.svg").write_text(svg + "\n", encoding="utf-8", newline="\n")
    css = css.replace(chevron.group(0), 'url("select-chevron.svg")')
    if ".gal" in css or "data:" in css:
        raise SystemExit("baleen.css still contains gallery rules or a data: URI")
    (out / "baleen.css").write_text(CSS_HEADER + FONT_FACE + css, encoding="utf-8", newline="\n")


def build_sprite(sprite: str, out: Path) -> None:
    svg = sprite.replace('style="display:none"', 'class="sprite"', 1)
    header = ("<!-- Lucide icons (ISC licence, https://lucide.dev), the design prototype's sprite. "
              "GENERATED by scripts/vendor_assets.py. -->\n")
    out.write_text(header + svg + "\n", encoding="utf-8", newline="\n")


# --------------------------------------------------------------------------- lucide check


_ELEM = re.compile(r"<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)/?>")
_ATTR = re.compile(r'([a-zA-Z-]+)="([^"]*)"')


def _shape_set(svg_inner: str) -> list[tuple[str, tuple[tuple[str, str], ...]]]:
    shapes = []
    for tag, attrs in _ELEM.findall(svg_inner):
        a = tuple(sorted((k, v) for k, v in _ATTR.findall(attrs) if k not in ("class",)))
        shapes.append((tag, a))
    return sorted(shapes)


def check_lucide(sprite: str, lucide_pkg: Path) -> list[str]:
    report: list[str] = []
    for sid, inner in re.findall(r'<symbol id="i-([\w-]+)" viewBox="0 0 24 24">(.*?)</symbol>', sprite, re.S):
        names = LUCIDE_NAMES.get(sid)
        if not names:
            report.append(f"i-{sid}: no Lucide mapping")
            continue
        found = None
        for n in names:
            p = lucide_pkg / "icons" / f"{n}.svg"
            if p.exists():
                found = (n, p.read_text(encoding="utf-8"))
                break
        if not found:
            report.append(f"i-{sid}: lucide-static has no {' / '.join(names)}")
            continue
        n, text = found
        if _shape_set(inner) == _shape_set(text):
            report.append(f"i-{sid}: matches {n}")
        else:
            report.append(f"i-{sid}: DIFFERS from {n} (prototype kept)")
    return report


# --------------------------------------------------------------------------- fonts


def subset_fonts(pins: dict, pkgs: dict[str, Path], out: Path) -> None:
    """Subset each face to the design §03 ranges. Fontsource's `latin` file is the source; no
    fontsource subset carries the → arrow (U+2192), so that glyph falls back to the system font."""
    out.mkdir(parents=True, exist_ok=True)
    tool = pins["pyftsubset"]
    base = ["uv", "run", "--no-project", "--quiet", "--with", f"fonttools=={tool['fonttools']}",
            "--with", f"brotli=={tool['brotli']}"]
    for spec in pins["fonts"]:
        src = pkgs[spec["package"]] / "files" / f"{spec['family']}-{pins['font_subset']}-{spec['weight']}-normal.woff2"
        if not src.exists():
            raise SystemExit(f"no source font for {spec}")
        dest = out / spec["out"]
        subprocess.run([
            *base, "pyftsubset", str(src), f"--unicodes={pins['unicodes']}", "--flavor=woff2",
            f"--layout-features={pins['layout_features']}", "--name-IDs=*", "--name-languages=*",
            "--no-hinting", "--desubroutinize", f"--output-file={dest}",
        ], check=True)
        print(f"font {spec['out']}: {dest.stat().st_size / 1024:.1f} KB")


# --------------------------------------------------------------------------- build


def build(pins: dict, cache: Path, root: Path) -> list[str]:
    static = root / "src" / "baleen" / "static"
    templates = root / "src" / "baleen" / "templates"
    notices = root / "THIRD_PARTY_NOTICES" / "assets"
    for d in (static, static / "fonts", static / "brand", templates / "partials", notices):
        d.mkdir(parents=True, exist_ok=True)
    pkgs = {name: fetch_package(name, pin, cache) for name, pin in pins["npm"].items()}

    shutil.copyfile(pkgs["htmx.org"] / "dist" / "htmx.min.js", static / "htmx.min.js")

    parts = prototype_parts()
    build_css(parts["style"], static)
    build_sprite(parts["sprite"], templates / "partials" / "icons.svg")
    fav = base64.b64decode(parts["favicon"]).decode("utf-8")
    if "PLACEHOLDER" not in fav:
        raise SystemExit("prototype favicon lost its PLACEHOLDER marker")
    (static / "favicon.svg").write_text(fav + "\n", encoding="utf-8", newline="\n")
    (static / "brand" / "walking-whale.png").write_bytes(base64.b64decode(parts["logo"]))

    subset_fonts(pins, pkgs, static / "fonts")

    licences = {
        "htmx.org": "htmx-0BSD.txt",
        "@fontsource/inter": "Inter-OFL.txt",
        "@fontsource/ibm-plex-mono": "IBMPlexMono-OFL.txt",
        "@fontsource/cormorant-garamond": "CormorantGaramond-OFL.txt",
        "lucide-static": "Lucide-ISC.txt",
    }
    for name, fname in licences.items():
        src = next((p for p in (pkgs[name] / "LICENSE", pkgs[name] / "LICENSE.md", pkgs[name] / "LICENSE.txt")
                    if p.exists()), None)
        if src is None:
            raise SystemExit(f"{name}: no licence file in the package")
        head = f"{name} {pins['npm'][name]['version']} ({pins['npm'][name]['license']})\n\n"
        (notices / fname).write_text(head + src.read_text(encoding="utf-8").replace("\r\n", "\n"),
                                     encoding="utf-8", newline="\n")
    return check_lucide(parts["sprite"], pkgs["lucide-static"])


