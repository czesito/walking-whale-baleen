"""Build the vendored front-end assets (design handoff §12, spec §4, DR-03).

    python scripts/vendor_assets.py --cache DIR          # build and write the assets
    python scripts/vendor_assets.py --cache DIR --check  # rebuild in a temp folder, compare
    python scripts/vendor_assets.py --cache DIR --pin    # record registry integrity in assets.json

What it writes (all committed):

- src/baleen/static/htmx.min.js            htmx 2.x from the htmx.org npm tarball
- src/baleen/static/fonts/*.woff2          Inter 400/500/600, IBM Plex Mono 400/500, Cormorant
                                           Garamond 600, subset with pyftsubset (design §03)
- src/baleen/static/baleen.css             the prototype's <style> block minus the .gal rules
                                           (the Google Fonts link is not in it), plus the handoff
                                           @font-face block; the select chevron data: URI becomes
                                           select-chevron.svg because the CSP (SEC-6) has no
                                           data: image source
- src/baleen/static/select-chevron.svg     that chevron
- src/baleen/static/favicon.svg            the prototype's placeholder favicon (PLACEHOLDER)
- src/baleen/static/brand/walking-whale.png  the Walking Whale logo used in About (a Walking
                                           Whale trademark, not covered by Apache-2.0)
- src/baleen/templates/partials/icons.svg  the prototype's inline Lucide sprite
- THIRD_PARTY_NOTICES/assets/*             licence texts (0BSD, OFL-1.1, ISC)

npm tarballs are downloaded over HTTPS and verified against the sha512 integrity recorded in
scripts/assets.json and the registry metadata. Tarballs are unpacked with tarfile (no Node.js).
pyftsubset runs from an ephemeral `uv run --with fonttools --with brotli`, so fonttools is never
part of the project locks.
"""

