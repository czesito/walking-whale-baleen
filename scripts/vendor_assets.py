def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--cache", type=Path, default=ROOT / ".scratch" / "assets-cache",
                    help="download and unpack folder (default: .scratch/assets-cache)")
    ap.add_argument("--check", action="store_true", help="rebuild in a temp folder and compare with the repo")
    ap.add_argument("--pin", action="store_true", help="record the registry integrity of every pinned package")
    ns = ap.parse_args(argv)
    pins = json.loads(PINS.read_text(encoding="utf-8"))
    ns.cache.mkdir(parents=True, exist_ok=True)
    if ns.pin:
        pin_integrity(pins)
        return 0
    if any(not p.get("integrity") for p in pins["npm"].values()):
        raise SystemExit("assets.json has packages without an integrity pin; run with --pin first")
    if ns.check:
        with tempfile.TemporaryDirectory() as td:
            tmp = Path(td)
            build(pins, ns.cache, tmp)
            bad = [rel for rel in OUTPUTS if not filecmp.cmp(tmp / rel, ROOT / rel, shallow=False)]
            fonts = sorted(p.name for p in (tmp / "src/baleen/static/fonts").glob("*.woff2"))
            bad += [f"fonts/{f}" for f in fonts
                    if not filecmp.cmp(tmp / "src/baleen/static/fonts" / f, ROOT / "src/baleen/static/fonts" / f,
                                       shallow=False)]
        if bad:
            print("out of date:", *bad, sep="\n  ")
            return 1
        print("all vendored assets are up to date")
        return 0
    for line in build(pins, ns.cache, ROOT):
        print(line)
    return 0


if __name__ == "__main__":
    sys.exit(main())
